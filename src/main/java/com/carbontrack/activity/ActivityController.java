
package com.carbontrack.activity;

import com.carbontrack.user.AppUser;
import com.carbontrack.user.AppUserRepository;

import org.springframework.http.HttpStatus;
import org.springframework.security.core.Authentication;
import org.springframework.web.bind.annotation.*;
import org.springframework.web.server.ResponseStatusException;

import java.time.LocalDate;
import java.util.List;

@RestController
@RequestMapping("/api/activities")
@CrossOrigin(origins = "${app.cors.allowed-origins:http://localhost:3000}", allowCredentials = "true")
public class ActivityController {

    private final ActivityRepository repository;
    private final AppUserRepository userRepository;

    public ActivityController(
            ActivityRepository repository,
            AppUserRepository userRepository) {
        this.repository = repository;
        this.userRepository = userRepository;
    }

    private AppUser currentUser(Authentication authentication) {
        if (authentication == null || !authentication.isAuthenticated()) {
            throw new ResponseStatusException(
                HttpStatus.UNAUTHORIZED, "Please log in");
        }

        return userRepository.findByEmailIgnoreCase(
                authentication.getName())
            .orElseThrow(() -> new ResponseStatusException(
                HttpStatus.UNAUTHORIZED, "User not found"));
    }

    private Activity ownedActivity(Long id, Long userId) {
        return repository.findByIdAndUser_Id(id, userId)
            .orElseThrow(() -> new ResponseStatusException(
                HttpStatus.NOT_FOUND, "Activity not found"));
    }

    @GetMapping
    public List<Activity> getAllActivities(Authentication authentication) {
        AppUser user = currentUser(authentication);
        return repository.findAllByUser_IdOrderByActivityDateDesc(
            user.getId());
    }

    @GetMapping("/{id}")
    public Activity getActivityById(
            @PathVariable Long id,
            Authentication authentication) {
        AppUser user = currentUser(authentication);
        return ownedActivity(id, user.getId());
    }

    @PostMapping
    @ResponseStatus(HttpStatus.CREATED)
    public Activity createActivity(
            @RequestBody Activity activity,
            Authentication authentication) {
        AppUser user = currentUser(authentication);

        activity.setUser(user);
        if (activity.getActivityDate() == null) {
            activity.setActivityDate(LocalDate.now());
        }

        // Never trust a client-supplied ID when creating a new activity.
        // The entity ID is generated by the database.
        return repository.save(activity);
    }

    @PutMapping("/{id}")
    public Activity updateActivity(
            @PathVariable Long id,
            @RequestBody Activity updatedActivity,
            Authentication authentication) {
        AppUser user = currentUser(authentication);
        Activity existing = ownedActivity(id, user.getId());

        existing.setActivityDate(
            updatedActivity.getActivityDate() == null
                ? existing.getActivityDate()
                : updatedActivity.getActivityDate());
        existing.setName(updatedActivity.getName());
        existing.setTransport(updatedActivity.getTransport());
        existing.setElectricity(updatedActivity.getElectricity());
        existing.setFood(updatedActivity.getFood());
        existing.setTotal(updatedActivity.getTotal());

        return repository.save(existing);
    }

    @DeleteMapping("/{id}")
    @ResponseStatus(HttpStatus.NO_CONTENT)
    public void deleteActivity(
            @PathVariable Long id,
            Authentication authentication) {
        AppUser user = currentUser(authentication);
        Activity existing = ownedActivity(id, user.getId());
        repository.delete(existing);
    }
}
